// ทดสอบตัวตรวจความสอดคล้องของบัญชี (tools/check-ledger.js) · รัน: node tests/ledger.test.js
const {checkSummary,checkTkw}=require('../tools/check-ledger.js');
const SUM='สรุปประจำวัน';
const S=(ym,ymC,rp,rpC,tk,tkC,kh,khC)=>[{type:'ย/ม',amount:ym,count:ymC},{type:'รับจำนำ',amount:rp,count:rpC},{type:'ไถ่ถอน',amount:tk,count:tkC},{type:'คงเหลือ',amount:kh,count:khC}];
const R=(t,b,a)=>({type:'ส',ticket:t,book:b,amount:a});
const day=(rows,sum,months=['พฤศจิกายน'])=>({months,data:{[months[0]]:rows,[SUM]:sum}});

let fail=0; const ok=(c,m)=>{ if(!c){fail++;console.log('FAIL',m);} else console.log('ok  ',m); };
const kinds=i=>i.map(x=>x.day+':'+x.kind).join(',');

{ // 1) ข้อมูลปกติ: วันว่าง → วันแรกมียอดเปิด → วันหยุด → วันทำงาน ผ่านหมด
  const db={
    '2026-11-05':day([],S(0,0,0,0,0,0,0,0)),
    '2026-11-06':day([R('1','10',1000),R('2','10',2000)],S(100000,50,3500,3,3000,2,100500,51)), // ยอดเปิดครั้งแรก (วันก่อนเป็น 0) ยกมาไม่ต้องต่อเนื่อง
    '2026-11-07':day([],S(100500,51,0,0,0,0,100500,51)),
    '2026-11-09':day([R('3','11',500)],S(100500,51,700,1,500,1,100700,51)),
  };
  ok(checkSummary(db).length===0,'1 ข้อมูลปกติ (ยอดเปิดครั้งแรก วันหยุด ข้ามวัน) ไม่มีข้อผิดพลาด');
}
{ // 2) สูตรไม่ตรง
  const db={'2026-11-06':day([R('1','10',1000)],S(100000,50,0,0,1000,1,99999,49))};
  ok(kinds(checkSummary(db))==='2026-11-06:สูตรไม่ตรง','2 คงเหลือผิด 1 บาท → จับได้ (เฉพาะสูตรเงิน จำนวนรายถูก)');
}
{ // 3) จำนวนรายไม่ตรง
  const db={'2026-11-06':day([R('1','10',1000)],S(100000,50,0,0,1000,1,99000,50))};
  ok(kinds(checkSummary(db))==='2026-11-06:จำนวนรายไม่ตรง','3 จำนวนรายคงเหลือผิด → จับได้');
}
{ // 4) ยกมาไม่ต่อเนื่อง (ข้ามวันหยุด)
  const db={
    '2026-11-06':day([R('1','10',1000)],S(100000,50,0,0,1000,1,99000,49)),
    '2026-11-07':day([],S(99000,49,0,0,0,0,99000,49)),
    '2026-11-09':day([R('2','10',500)],S(98000,49,0,0,500,1,97500,48)),
  };
  ok(kinds(checkSummary(db))==='2026-11-09:ยกมาไม่ต่อเนื่อง','4 ย/ม ไม่เท่าคงเหลือวันก่อน (ข้ามวันหยุด) → จับได้วันที่ 9');
}
{ // 5) ไถ่ถอนไม่เท่ากับตั๋วในตาราง
  const db={'2026-11-06':day([R('1','10',1000),R('2','10',2000)],S(100000,50,0,0,2500,2,97500,48))};
  ok(kinds(checkSummary(db))==='2026-11-06:ไถ่ถอนไม่เท่าตั๋วในตาราง','5 ไถ่ถอนในสรุปไม่เท่าผลรวมตั๋ว → จับได้');
}
{ // 6) แถวว่าง/เลขตั๋วว่างไม่ถูกนับ
  const db={'2026-11-06':day([R('1','10',1000),{type:'',ticket:'',amount:'',book:''},R('  ','10',999)],S(100000,50,0,0,1000,1,99000,49))};
  ok(checkSummary(db).length===0,'6 แถวว่าง/เลขตั๋วเป็นช่องว่างไม่ถูกนับ');
}
{ // 7) เทียบตารางเขียนตั๋ว: ปัญหา 4 แบบที่เจอในข้อมูลจริงวันที่ 12 พ.ย.
  const k='2026-11-12';
  const db={[k]:day([R('2235','254',26500),R('2327','255',51500),R('2329','255',51500),R('2293','150',55000),R('100','1',1000)],S(0,0,0,0,0,0,0,0))};
  const store={[k]:{m:[6,1],r:[[['2235','51500','254'],['2329','51500',''],['2293','55000','150'],['100','1000','1']],[['2293','55000','150']]]}};
  const r=checkTkw(db,store,k);
  ok(r.amountDiffs.length===1&&r.amountDiffs[0].t==='2235'&&r.amountDiffs[0].tkw===51500&&r.amountDiffs[0].ledger===26500,'7a ยอดเงินต่างกัน (2235 เล่ม 254: 51,500 กับ 26,500)');
  ok(r.duplicatesInTkw.length===1&&r.duplicatesInTkw[0].key==='2293|150'&&r.duplicatesInTkw[0].times===2,'7b ตั๋วซ้ำในตารางเขียนตั๋ว (2293 เล่ม 150 สองครั้ง)');
  ok(r.missingBook.length===1&&r.missingBook[0].t==='2329','7c ตั๋วที่ไม่มีเล่มที่ (2329)');
  ok(r.onlyInLedger.map(x=>x.t+'|'+x.b).sort().join()==='2327|255,2329|255'&&r.onlyInTkw.map(x=>x.t+'|'+x.b).join()==='2329|','7d ตั๋วที่มีฝั่งเดียว (2327 ไม่มีในตาราง / 2329 เล่มไม่ตรง)');
  ok(r.diffSum===r.amountDiffs[0].tkw-r.amountDiffs[0].ledger+55000-51500,'7e ผลต่างรวม = ผลต่างรายใบรวมกัน (25,000 + ตั๋วซ้ำ 55,000 − ที่ขาด 51,500)');
}
{ // 8) ตรงกันทั้งหมด
  const k='2026-11-12';
  const db={[k]:day([R('1','10',1000),R('2','10',2000)],S(0,0,0,0,0,0,0,0))};
  const store={[k]:{m:[11],r:[[['1','1000','10'],['2','2000','10']]]}};
  const r=checkTkw(db,store,k);
  ok(!r.onlyInTkw.length&&!r.onlyInLedger.length&&!r.amountDiffs.length&&!r.duplicatesInTkw.length&&!r.missingBook.length&&r.diffSum===0,'8 ตรงกันทั้งหมด → ไม่มีข้อผิดพลาด');
  ok(checkTkw(db,{},k).tkwRows===0&&checkTkw(db,{},k).onlyInLedger.length===2,'8b ไม่มีข้อมูลตารางเขียนตั๋วของวันนั้น → ไม่พัง แจ้งว่าขาดทั้งหมด');
}
console.log(fail?`❌ ล้มเหลว ${fail}`:'✅ ผ่านทั้งหมด'); process.exit(fail?1:0);
